export function t(source: string, params: Record<string, string | number> = {}): string {
  let text = source
  if (locale.value === 'en-US' && Object.hasOwn(english, source)) {
    text = (params.count === 1 || params.count === '1') && Object.hasOwn(singular, source) ? singular[source]! : english[source]!
  }
  return text.replace(/\{(\w+)\}/g, (token, key: string) => params[key] === undefined ? token : String(params[key]))
}

export const number = (value: number) => value.toLocaleString(locale.value)

export function localizeMessage(message: string): string {
  if (locale.value !== 'en-US') return message
  if (Object.hasOwn(english, message)) return english[message]!
  if (message.startsWith('无法获取执行状态：')) return t('无法获取执行状态：{error}', { error: localizeMessage(message.slice('无法获取执行状态：'.length)) })
  const request = /^请求失败（(\d+)），请查看连接诊断。$/.exec(message)
  if (request) return t('请求失败（{status}），请查看连接诊断。', { status: request[1]! })
  // Translate only the known prefix; file names and platform/OS details stay verbatim.
  const separator = message.indexOf(': ')
  if (separator > 0 && Object.hasOwn(english, message.slice(0, separator))) return `${english[message.slice(0, separator)]}: ${message.slice(separator + 2)}`
  return message
}
